const {test,before,after}=require('node:test');
const assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
const {createServer}=require('../scripts/serve-probe.cjs');
let server,browser,origin;
before(async()=>{server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));origin='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true});});
after(async()=>{await browser?.close();if(server)await new Promise(r=>server.close(r));});
for(const width of [320,390,768,1280]) test('exercise library reads and selects without mutation at '+width+'px',async t=>{
  const context=await browser.newContext({viewport:{width,height:900}});t.after(()=>context.close());
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/api/**',r=>r.fulfill({json:{enabled:false}}));
  await page.goto(origin);
  const fixture=await page.evaluate(()=>{
    const name='Single Arm Cable Rope Triceps Pressdown With A Very Long Exercise Name';
    const id='99999999-9999-4999-8999-999999999937',unused='99999999-9999-4999-8999-999999999938';
    db=emptyData();db.exerciseLibrary={[id]:{primary:'Triceps',secondary:[],pattern:'extension',type:'cable',status:'accessory'},[unused]:{primary:'',secondary:[],pattern:'',type:'',status:''}};
    db.sets=[{id:'synthetic',exercise:id,date:'2026-11-08',weight:0,reps:8,unit:'lb',complete:true,notes:'Keep exact',pain:0}];
    cloudController={getWorkoutState:()=>({catalog:{exercises:[{id,displayName:name},{id:unused,displayName:'Uncategorized unused exercise'}]},data:db})};
    window.fixtureBefore=JSON.stringify(db);window.storageBefore=localStorage.getItem('daveGymTrackerV1');renderAll();
    return {id,name};
  });
  await page.locator('[data-view="exercises"]').click();
  const button=page.getByRole('button',{name:fixture.name,exact:true});
  assert.equal(await button.count(),1);
  const row=button.locator('xpath=ancestor::tr');
  assert.equal(await row.locator('td').nth(3).textContent(),'1');
  assert.equal(await row.locator('td').nth(4).textContent(),'1');
  assert.equal(await row.evaluate(el=>getComputedStyle(el).display),width<=600?'grid':'table-row');
  await page.getByRole('button',{name:'Uncategorized unused exercise',exact:true}).click();
  await button.focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('#exerciseDetailTitle').textContent(),fixture.name);
  assert.equal(await button.getAttribute('aria-pressed'),'true');
  assert.equal(await button.getAttribute('aria-controls'),'exerciseDetail');
  assert.equal(await button.evaluate(el=>getComputedStyle(el).outlineStyle),'solid');
  assert(await button.evaluate(el=>el.getBoundingClientRect().height>=44));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert(await page.locator('#exerciseTable').evaluate(el=>el.scrollWidth<=el.clientWidth));
  if(width<=600)assert(await button.evaluate(el=>el.clientWidth>=el.closest('tr').clientWidth-2));
  assert(await page.evaluate(()=>JSON.stringify(db)===window.fixtureBefore&&localStorage.getItem('daveGymTrackerV1')===window.storageBefore));
  assert.deepEqual(errors,[]);
});
